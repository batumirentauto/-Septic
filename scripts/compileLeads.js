import fs from 'fs-extra'
import path from 'path'
import * as XLSXModule from 'xlsx'

const XLSX = XLSXModule.default || XLSXModule

function slugify(text) {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_-]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

async function compile() {
  const xlsxPath = path.resolve('./septic_repair/companies.xlsx')
  if (!(await fs.pathExists(xlsxPath))) {
    console.error('companies.xlsx not found at', xlsxPath)
    process.exit(1)
  }

  const wb = XLSX.readFile(xlsxPath)
  const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]])
  console.log(`[Compile] Found ${rows.length} rows in companies.xlsx`)

  const leads = []
  const slugs = new Set()

  for (const row of rows) {
    const name = row['Название']
    if (!name) continue

    let slug = slugify(name)
    if (!slug) slug = 'company-' + (leads.length + 1)
    if (slugs.has(slug)) {
      const st = (row['Штат'] || '').toLowerCase()
      slug = `${slug}-${st}`
    }
    let counter = 1
    const baseSlug = slug
    while (slugs.has(slug)) {
      slug = `${baseSlug}-${counter}`
      counter++
    }
    slugs.add(slug)

    const folderName = row['Папка с файлами'] || name
    const companyDir = path.resolve('./septic_repair', folderName)

    let reviews = []
    let photos = []
    if (await fs.pathExists(companyDir)) {
      const revPath = path.join(companyDir, 'reviews.json')
      if (await fs.pathExists(revPath)) {
        try {
          reviews = await fs.readJson(revPath)
        } catch {}
      }
      const ownerPhotosDir = path.join(companyDir, 'photos', 'owner')
      if (await fs.pathExists(ownerPhotosDir)) {
        try {
          const files = await fs.readdir(ownerPhotosDir)
          photos = files
            .filter((f) => f.endsWith('.jpg') || f.endsWith('.png') || f.endsWith('.jpeg'))
            .map((f) => `/showcase/${encodeURIComponent(folderName)}/photos/owner/${f}`)
        } catch {}
      }
    }

    leads.push({
      slug,
      name,
      state: row['Штат'] || '',
      city: row['Город'] || '',
      address: row['Адрес'] && row['Адрес'] !== 'Не указан' ? row['Адрес'] : `${row['Город'] || ''}, ${row['Штат'] || ''} (Service Area)`,
      phone: row['Контактный номер'] || '',
      rating: Number(row['Оценка'] || 5),
      reviewCount: Number(row['Количество отзывов'] || 0),
      hasWebsite: row['Наличие сайта'] === 'Есть',
      website: row['Ссылка на сайт'] || '',
      websiteIssue: row['Проблема с сайтом'] || '',
      mapsUrl: row['Ссылка на Google Maps'] || '',
      category: row['Категория'] || 'Septic system service',
      hours: row['Рабочие часы'] || 'Monday - Saturday: 7:00 AM - 7:00 PM | 24/7 Emergency Service',
      photosCount: Number(row['Собрано фото'] || 0),
      reviewsCount: Number(row['Собрано отзывов'] || 0),
      folderName,
      reviewsSample: reviews.slice(0, 10),
      photosSample: photos.slice(0, 8),
    })
  }

  await fs.ensureDir('./src/data')
  await fs.writeJson('./src/data/septicLeads.json', leads, { spaces: 2 })

  // Write TypeScript wrapper
  const tsContent = `// Auto-generated by scripts/compileLeads.js
import rawLeads from './septicLeads.json'

export interface ReviewItem {
  author: string
  authorMeta?: string
  rating: number
  date?: string
  text: string
  photos?: string[]
}

export interface SepticLead {
  slug: string
  name: string
  state: string
  city: string
  address: string
  phone: string
  rating: number
  reviewCount: number
  hasWebsite: boolean
  website: string
  websiteIssue: string
  mapsUrl: string
  category: string
  hours: string
  photosCount: number
  reviewsCount: number
  folderName: string
  reviewsSample: ReviewItem[]
  photosSample: string[]
}

export const septicLeads: SepticLead[] = rawLeads as SepticLead[]

export function getLeadBySlug(slug: string): SepticLead | undefined {
  return septicLeads.find((l) => l.slug === slug)
}

export function getAllSlugs(): string[] {
  return septicLeads.map((l) => l.slug)
}
`
  await fs.writeFile('./src/data/septicLeads.ts', tsContent, 'utf-8')
  console.log(`[Compile Complete] Compiled ${leads.length} leads into src/data/septicLeads.json & septicLeads.ts`)
}

compile().catch((err) => {
  console.error('[Compile Error]:', err)
  process.exit(1)
})
