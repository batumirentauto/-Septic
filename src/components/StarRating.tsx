'use client'

import React from 'react'

interface StarRatingProps {
  rating: number
  maxRating?: number
  className?: string
  starClassName?: string
}

export function StarRating({
  rating,
  maxRating = 5,
  className = '',
  starClassName = 'w-4 h-4',
}: StarRatingProps) {
  const stars = []

  for (let i = 1; i <= maxRating; i++) {
    if (rating >= i) {
      // Full Star
      stars.push(
        <div key={i} className="relative inline-block text-amber-400">
          <svg className={`${starClassName} fill-current`} viewBox="0 0 20 20">
            <path d="M9.049 2.927c.3-.921 1.603-.921 1.902 0l1.07 3.292a1 1 0 00.95.69h3.462c.969 0 1.371 1.24.588 1.81l-2.8 2.034a1 1 0 00-.364 1.118l1.07 3.292c.3.921-.755 1.688-1.54 1.118l-2.8-2.034a1 1 0 00-1.175 0l-2.8 2.034c-.784.57-1.838-.197-1.539-1.118l1.07-3.292a1 1 0 00-.364-1.118L2.98 8.72c-.783-.57-.38-1.81.588-1.81h3.461a1 1 0 00.951-.69l1.07-3.292z" />
          </svg>
        </div>
      )
    } else if (rating > i - 1 && rating < i) {
      // Fractional Star
      const fillPercent = Math.round((rating - (i - 1)) * 100)
      stars.push(
        <div key={i} className="relative inline-block text-slate-600">
          {/* Background Empty Star */}
          <svg className={`${starClassName} fill-current`} viewBox="0 0 20 20">
            <path d="M9.049 2.927c.3-.921 1.603-.921 1.902 0l1.07 3.292a1 1 0 00.95.69h3.462c.969 0 1.24.588 1.81l-2.8 2.034a1 1 0 00-.364 1.118l1.07 3.292c.3.921-.755 1.688-1.54 1.118l-2.8-2.034a1 1 0 00-1.175 0l-2.8 2.034c-.784.57-1.838-.197-1.539-1.118l1.07-3.292a1 1 0 00-.364-1.118L2.98 8.72c-.783-.57-.38-1.81.588-1.81h3.461a1 1 0 00.951-.69l1.07-3.292z" />
          </svg>
          {/* Foreground Partial Star */}
          <div
            className="absolute top-0 left-0 overflow-hidden text-amber-400"
            style={{ width: `${fillPercent}%` }}
          >
            <svg className={`${starClassName} fill-current max-w-none`} viewBox="0 0 20 20">
              <path d="M9.049 2.927c.3-.921 1.603-.921 1.902 0l1.07 3.292a1 1 0 00.95.69h3.462c.969 0 1.24.588 1.81l-2.8 2.034a1 1 0 00-.364 1.118l1.07 3.292c.3.921-.755 1.688-1.54 1.118l-2.8-2.034a1 1 0 00-1.175 0l-2.8 2.034c-.784.57-1.838-.197-1.539-1.118l1.07-3.292a1 1 0 00-.364-1.118L2.98 8.72c-.783-.57-.38-1.81.588-1.81h3.461a1 1 0 00.951-.69l1.07-3.292z" />
            </svg>
          </div>
        </div>
      )
    } else {
      // Empty Star
      stars.push(
        <div key={i} className="relative inline-block text-slate-700">
          <svg className={`${starClassName} fill-current`} viewBox="0 0 20 20">
            <path d="M9.049 2.927c.3-.921 1.603-.921 1.902 0l1.07 3.292a1 1 0 00.95.69h3.462c.969 0 1.24.588 1.81l-2.8 2.034a1 1 0 00-.364 1.118l1.07 3.292c.3.921-.755 1.688-1.54 1.118l-2.8-2.034a1 1 0 00-1.175 0l-2.8 2.034c-.784.57-1.838-.197-1.539-1.118l1.07-3.292a1 1 0 00-.364-1.118L2.98 8.72c-.783-.57-.38-1.81.588-1.81h3.461a1 1 0 00.951-.69l1.07-3.292z" />
          </svg>
        </div>
      )
    }
  }

  return <div className={`inline-flex items-center gap-0.5 ${className}`}>{stars}</div>
}
